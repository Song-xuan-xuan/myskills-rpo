#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────
# 监控脚本模板 —— 复制到 <项目>/.monitor/<服务名>.sh 后改 3 个变量
#
# 规矩：这个文件只回答三个问题。循环、锁、心跳、超时、报错检测、截断、
#       重试全部由 ~/.notify/lib.sh 提供，不要在这里重写。
# ─────────────────────────────────────────────────────────────────────

# ① 叫什么（小写连字符，与文件名一致）
SVC='__服务名__'

# ② 怎么判断「真的好了」：退出码 0 = 好了。
#    必须用【产物】而不是【过程文件】；若只能用过程文件，别忘了设 STABLE。
CHECK='__判断命令__'

# ③ 好了之后推什么：stdout 最后一行就是手机通知的正文。
BODY='__摘要命令__'

# ── 按需调整（不用就删掉）────────────────────────────────────────────
INTERVAL=30          # 多久检查一次（秒）
STABLE=0             # 判断通过后再等几秒复检，防「文件写到一半就被当完成」
HEARTBEAT=1800       # 每 30 分钟打一行「还在等」，0=关。别关，它是脚本的呼吸
TIMEOUT=0            # 最长等多久（秒），0=无限。长任务建议设成预期的 1.5 倍
# WATCH_PID=$$       # 目标进程 PID；它消失而条件没满足 → 立即告警「异常终止」
# WATCH_PATTERN='python train.py'   # 或者用命令行特征探测
BODY_MAX=300         # 推送正文最多多少字符（按字符截，不会切坏中文）
# TITLE_DONE="训练跑完了"          # 自定义通知标题

# ── 以下不用改 ──────────────────────────────────────────────────────
source "$HOME/.notify/lib.sh"

# --help 打印本文件头部说明；--test 发一条测试消息后退出
case "${1:-}" in
    --help) sed -n '2,32p' "$0"; exit 0 ;;
    --test)
        NOTIFY_SVC="$SVC" "$HOME/.notify/notify" done \
            "【测试】$SVC 通道自检" \
            "这是测试消息，不是任务完成。收到说明链路通畅。"
        exit $?
        ;;
esac

monitor_loop
